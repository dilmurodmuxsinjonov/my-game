    def test_supply_chain_production_cycle(self):
        """Verify resource balance in supply chain calculations."""
        inventory = {
            "wheat": 20,
            "bread": 50,
            "logs": 30,
            "stone": 25,
            "iron_ore": 10,
            "tools": 10
        }
        assigned = {
            "farmer": 2,
            "baker": 1,
            "lumberjack": 2,
            "miner": 1
        }
        
        # 1. Farmers produce 4 wheat per farmer
        wheat_prod = assigned["farmer"] * 4
        inventory["wheat"] += wheat_prod
        
        # 2. Baker consumes up to 2 wheat to produce 4 bread
        wheat_needed = assigned["baker"] * 2
        wheat_used = min(inventory["wheat"], wheat_needed)
        inventory["wheat"] -= wheat_used
        inventory["bread"] += wheat_used * 2
        
        # 3. Citizens consume 1 bread each
        total_citizens = sum(assigned.values())
        bread_eaten = min(inventory["bread"], total_citizens)
        inventory["bread"] -= bread_eaten
        
        self.assertEqual(inventory["wheat"], 26) # 20 + 8 - 2 = 26
        self.assertEqual(inventory["bread"], 48) # 50 + 4 - 6 = 48
        self.assertGreater(inventory["bread"], 0)

