        # Attempt to pour different metal (iron) -> rejected
        poured_diff = pour("iron", 4)
        self.assertEqual(poured_diff, 0)
        self.assertEqual(basin["units"], 5)

        # Complete pour with remaining 4 bronze
        poured_second = pour("bronze", 4)
        self.assertEqual(poured_second, 4)
        self.assertTrue(basin["is_solid"])
        self.assertEqual(basin["output"], "bronze_block")

