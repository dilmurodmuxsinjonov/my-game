    def test_rimworld_do_until_x_quota_thresholds(self):
        """Verify RimWorld-style 'Do Until X' production quotas prevent raw resource exhaustion."""
        DO_FOREVER = 0
        DO_UNTIL_X = 1
        PAUSED = 2

        inventory = {"bread": 16, "wheat": 20, "tools": 10, "iron_ore": 10}
        quotas = {"bread": 20, "tools": 10}
        quota_modes = {"bread": DO_UNTIL_X, "tools": DO_UNTIL_X}

        def can_produce(item):
            mode = quota_modes.get(item, DO_FOREVER)
            if mode == PAUSED:
                return False
            if mode == DO_FOREVER:
                return True
            return inventory.get(item, 0) < quotas.get(item, 9999)

        # 1. Bread is under quota (16 < 20): can produce
        self.assertTrue(can_produce("bread"))

        # Baker bakes 4 bread (using 2 wheat) -> reaches 20
        needed_bread = quotas["bread"] - inventory["bread"]
        wheat_needed = (needed_bread + 1) // 2
        inventory["wheat"] -= wheat_needed
        inventory["bread"] += needed_bread
        self.assertEqual(inventory["bread"], 20)
        self.assertEqual(inventory["wheat"], 18)

        # Bread quota reached: can_produce returns False, preserving remaining 18 wheat!
        self.assertFalse(can_produce("bread"))

        # 2. Tools is already at quota (10 == 10): paused automatically
        self.assertFalse(can_produce("tools"))

        # 3. Switching to DO_FOREVER overrides limit
        quota_modes["tools"] = DO_FOREVER
        self.assertTrue(can_produce("tools"))

        # 4. Pausing halts production unconditionally
        quota_modes["tools"] = PAUSED
        self.assertFalse(can_produce("tools"))

