    def test_arrow_ballistic_flight_and_parabolic_trajectory(self):
        """Verify arrow physics: horizontal velocity, gravity integration, and drop distance."""
        speed = 36.0 # m/s
        gravity = 9.8 # m/s^2
        angle_deg = 15.0 # shot at 15 degree angle
        angle_rad = math.radians(angle_deg)
        
        vx = speed * math.cos(angle_rad)
        vy = speed * math.sin(angle_rad)
        
        # Flight time to travel 25 meters horizontally: t = d / vx
        t_25m = 25.0 / vx
        self.assertAlmostEqual(t_25m, 0.719, places=2)
        
        # Height at 25m: y(t) = y0 + vy*t - 0.5*g*t^2
        y0 = 1.6 # monarch eye height
        y_at_25m = y0 + (vy * t_25m) - (0.5 * gravity * (t_25m ** 2))
        # Arrow should still be above ground
        self.assertGreater(y_at_25m, 0.0)
        self.assertAlmostEqual(y_at_25m, 5.86, delta=0.5)

