    def test_season_manager_cycle_and_temperatures(self):
        """Verify 4-season cycle, diurnal fluctuation, and weather temperature offsets."""
        base_temps = {
            "SPRING": 16.0,
            "SUMMER": 28.0,
            "AUTUMN": 11.0,
            "WINTER": -6.0
        }
        weather_mods = {
            "CLEAR": 0.0,
            "RAIN": -4.0,
            "THUNDERSTORM": -6.0,
            "SNOW": -8.0
        }

        # Calculate Midday Spring Clear (progress = 0.5)
        # sin((0.5 - 0.25) * 2pi) = sin(pi/2) = 1.0 => +5°C
        diurnal_midday = math.sin((0.5 - 0.25) * 2.0 * math.pi) * 5.0
        self.assertAlmostEqual(diurnal_midday, 5.0, places=3)
        temp_spring_noon = base_temps["SPRING"] + diurnal_midday + weather_mods["CLEAR"]
        self.assertAlmostEqual(temp_spring_noon, 21.0, places=3)

        # Calculate Midnight Winter Blizzard (progress = 0.0, weather = SNOW)
        # sin((0.0 - 0.25) * 2pi) = sin(-pi/2) = -1.0 => -5°C
        diurnal_midnight = math.sin((0.0 - 0.25) * 2.0 * math.pi) * 5.0
        self.assertAlmostEqual(diurnal_midnight, -5.0, places=3)
        temp_winter_blizzard = base_temps["WINTER"] + diurnal_midnight + weather_mods["SNOW"]
        self.assertAlmostEqual(temp_winter_blizzard, -19.0, places=3)

