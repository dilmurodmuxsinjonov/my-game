            logs = []
            # Bronze: 3 Cu + 1 Sn -> 4 Bronze (temp >= 950)
            if temp >= 950.0:
                cu = tank.get("copper", 0)
                sn = tank.get("tin", 0)
                batches = min(int(cu / 3), sn)
                if batches > 0:
                    tank["copper"] -= batches * 3
                    tank["tin"] -= batches
                    tank["bronze"] = tank.get("bronze", 0) + (batches * 4)
                    logs.append(f"Bronze x{batches}")
