        self.assertAlmostEqual(temp_spring_noon, 21.0, places=3)

        # Calculate Midnight Winter Blizzard (progress = 0.0, weather = SNOW)
        # sin((0.0 - 0.25) * 2pi) = sin(-pi/2) = -1.0 => -5°C
        diurnal_midnight = math.sin((0.0 - 0.25) * 2.0 * math.pi) * 5.0
        self.assertAlmostEqual(diurnal_midnight, -5.0, places=3)
        temp_winter_blizzard = base_temps["WINTER"] + diurnal_midnight + weather_mods["SNOW"]
        self.assertAlmostEqual(temp_winter_blizzard, -19.0, places=3)

