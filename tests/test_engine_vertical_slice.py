    def test_farmers_delight_crop_rotation_and_soil_fertility(self):
        """Verify 2x rich compost growth speed, rotation yield bonus, and monoculture penalty."""
        WHEAT = 0
        CABBAGE = 1
        
        # 1. Normal farmland vs Rich compost farmland
        def get_growth_speed(is_rich, history, crop):
            speed = 2.0 if is_rich else 1.0
            if len(history) >= 1 and history[-1] != crop:
                speed += 0.25 # Rotation bonus
            elif len(history) >= 2 and history[-1] == crop and history[-2] == crop:
                speed = max(0.5, speed - 0.20) # Monoculture penalty
            return speed

        def get_yield(is_rich, history, crop):
            base_yield = 2
            if is_rich:
                base_yield += 1
            if len(history) >= 1 and history[-1] != crop:
                base_yield += 1
            elif len(history) >= 2 and history[-1] == crop and history[-2] == crop:
                base_yield = max(1, base_yield - 1)
            return base_yield

        # Normal plot, first planting
        self.assertEqual(get_growth_speed(False, [], WHEAT), 1.0)
        self.assertEqual(get_yield(False, [], WHEAT), 2)

        # Rich compost plot, first planting: 2x speed!
        self.assertEqual(get_growth_speed(True, [], WHEAT), 2.0)
        self.assertEqual(get_yield(True, [], WHEAT), 3)

        # Alternating crop (Wheat -> Cabbage): +0.25 speed and +1 yield!
        rot_history = [WHEAT]
        self.assertEqual(get_growth_speed(True, rot_history, CABBAGE), 2.25)
        self.assertEqual(get_yield(True, rot_history, CABBAGE), 4) # 2 base + 1 rich + 1 rotation

        # Monoculture penalty (Wheat -> Wheat -> Wheat)
        mono_history = [WHEAT, WHEAT]
        self.assertEqual(get_growth_speed(False, mono_history, WHEAT), 0.80) # 1.0 - 0.20
        self.assertEqual(get_yield(False, mono_history, WHEAT), 1) # 2 base - 1 monoculture

