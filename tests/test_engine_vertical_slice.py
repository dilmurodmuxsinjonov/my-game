            if temp >= 1450.0:
                fe = tank.get("iron", 0)
                c = tank.get("carbon", 0)
                batches = min(fe, c)
                if batches > 0:
                    tank["iron"] -= batches
                    tank["carbon"] -= batches
                    tank["steel"] = tank.get("steel", 0) + batches
                    logs.append(f"Steel x{batches}")
            # Electrum: 1 Au + 1 Ag -> 2 Electrum (temp >= 1000)
            if temp >= 1000.0:
                au = tank.get("gold", 0)
                ag = tank.get("silver", 0)
                batches = min(au, ag)
                if batches > 0:
                    tank["gold"] -= batches
                    tank["silver"] -= batches
                    tank["electrum"] = tank.get("electrum", 0) + (batches * 2)
                    logs.append(f"Electrum x{batches}")
            return logs

