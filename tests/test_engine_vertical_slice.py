    def test_player_warmth_vitals_and_shelter_mechanics(self):
        """Verify warmth loss in freezing conditions, heat source protection, and ceiling shelter."""
        # Unprotected player in freezing temperature (-10°C)
        warmth = 100.0
        ambient_temp = -10.0
        is_sheltered = False
        near_heat_source = False
        delta = 1.0

        # Thermal decay rate
        def update_warmth(w, temp, sheltered, heat, dt):
            if heat:
                return min(100.0, w + 15.0 * dt)
            elif sheltered:
                if temp < 5.0:
                    return max(0.0, w - 0.8 * dt)
                return w
            else:
                if temp < 0.0:
                    chill = (0.0 - temp) * 0.4
                    return max(0.0, w - chill * dt)
                elif temp < 10.0:
                    return max(0.0, w - 0.5 * dt)
                return min(100.0, w + 2.0 * dt)

        # 5 seconds exposed in -10°C
        for _ in range(5):
            warmth = update_warmth(warmth, ambient_temp, is_sheltered, near_heat_source, delta)
        self.assertAlmostEqual(warmth, 80.0, places=1) # 100 - (10 * 0.4 * 5) = 80

        # Moving near a Campfire or Furnace restores warmth quickly
        near_heat_source = True
        for _ in range(2):
            warmth = update_warmth(warmth, ambient_temp, is_sheltered, near_heat_source, delta)
        self.assertAlmostEqual(warmth, 100.0, places=1) # 80 + 30 = 110 capped at 100

